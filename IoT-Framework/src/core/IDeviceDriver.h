// Фаза 1. Ключевое отличие драйвера от модуля (принцип 4 базовой
// архитектуры: "драйвер ≠ сервис"):
//
//   ДРАЙВЕР  — говорит с железом: регистры, пины, UART-протоколы, ISR.
//              НЕ является IModule, НЕ подписывается на шину, НЕ знает
//              о бизнес-логике. Результат работы отдаёт двумя способами:
//                1) публикация события в EventBus (факт: "карта считана");
//                2) синхронный вызов метода сервисом-владельцем ("сколько °C?").
//
//   СЕРВИС   — политика: пороги, правила, вердикты. Подписан на события
//              драйвера и/или опрашивает его через методы.
//
// Почему драйверы не модули (урок v4.2.2): там WiegandManager и
// TempSensorManager были полными модулями со своими подписками ANY_ID,
// мьютексами и logMessage — 400+ строк обвязки на 60 строк железной логики.
// Здесь драйвер — тонкий объект: реестр сам тикает его poll().
// ============================================================================
#pragma once

#include <cstdint>

class IDeviceDriver {
public:
    virtual ~IDeviceDriver() = default;

    // --- ИДЕНТИЧНОСТЬ ----------------------------------------------------
    /// Имя драйвера для реестра и логов: "esp_temp", "wiegand", "dfplayer".
    virtual const char* driverName() const = 0;

    // --- ЖИЗНЕННЫЙ ЦИКЛ (управляет DriverRegistry) --------------------------
    /// Инициализация железа. Вызывается реестром на фазе init() ядра —
    /// шины (BusManager) к этому моменту уже подняты.
    /// false — железо не отвечает; реестр пометит драйвер как failed.
    virtual bool init() = 0;

    /// Периодическая обработка (опрос датчика, разбор RX-буфера).
    /// Вызывается из tick() реестра не чаще getPollIntervalMs().
    /// Неблокирующая — бюджет, как у tick модулей (B2, 50 мс).
    virtual void poll() {}

    /// Минимальный период poll(), мс.
    virtual uint32_t getPollIntervalMs() const { return 1000; }

    // --- ЗДОРОВЬЕ --------------------------------------------------------------
    /// Жив ли драйвер (последний poll/init прошли без ошибок железа).
    /// HealthMonitor читает это через реестр.
    virtual bool isHealthy() const = 0;
};

#include <Arduino.h>
#include <cstdint>
#include <cstring>
#include <esp_event.h>

// ============================================================================
// ОБЪЯВЛЕНИЕ ШИН СОБЫТИЙ (определяются в AppCore.cpp)
// ============================================================================
ESP_EVENT_DECLARE_BASE(SH_SYS_EVENTS);
ESP_EVENT_DECLARE_BASE(SH_APP_EVENTS);

// ============================================================================
// 1. СТРУКТУРА ДАННЫХ ДЛЯ ПЕРЕДАЧИ СООБЩЕНИЙ
// ============================================================================
/**
 * @brief Универсальный контейнер для передачи данных между модулями
 *
 * Используется для:
 * - Отправки команд (SH_EVENT_CMD_EXECUTE)
 * - Ответов на команды (SH_EVENT_CMD_RESPONSE)
 * - Публикации статусов (SH_EVENT_MODULE_STATUS)
 * - Отправки ошибок (SH_EVENT_MODULE_ERROR)
 *
 * Все данные копируются в структуру и отправляются через шину событий.
 * ВАЖНО: payload должен содержать только текстовые данные (не бинарные)!
 */
struct ShEventData {
    uint32_t sourceModule;      // ID модуля-отправителя (0 = ядро)
    uint32_t targetModule;      // ID модуля-получателя (0 = всем)
    uint32_t command;           // Код команды (из ModuleCommands)
    int32_t value;              // Числовое значение (например, громкость, температура)
    char payload[128];          // Строковые данные (JSON, текст, ID карты)
    size_t payloadLen;          // Реальная длина payload (для безопасности)
};

// ============================================================================
// 2. КОНСТАНТЫ СОБЫТИЙ
// ============================================================================
constexpr int32_t SH_EVENT_USER_BASE = 0x1000;     // 4096 - начало пользовательских событий
constexpr int32_t SH_EVENT_MODULE_STATUS = 0x1000; // Статус модуля (вместо SH_EVENT_MODULE_TICK)

// ============================================================================
// 3. ID ВСЕХ МОДУЛЕЙ СИСТЕМЫ
// ============================================================================
/**
 * @brief Уникальные идентификаторы всех модулей
 *
 * Каждый модуль при регистрации в ядре получает свой ID.
 * Используется для адресации событий (sourceModule / targetModule).
 *
 * Диапазоны:
 * 0x0000 - 0x000F - Ядро и системные модули
 * 0x0005 - 0x000F - Аппаратные модули
 * 0x0010 - 0x001F - Сетевые модули
 * 0x0020 - 0x002F - Безопасность
 * 0x0030 - 0x003F - Системные сервисы
 * 0x1000 - 0x1FFF - Приложения (бизнес-логика)
 */
enum ModuleIds : uint32_t {
    // === ЯДРО И СИСТЕМНЫЕ МОДУЛИ (0x0000 - 0x000F) ===
    MODULE_ID_CORE     = 0x0000,   // Ядро системы (AppCore)
    MODULE_ID_CONFIG   = 0x0001,   // Менеджер конфигурации
    MODULE_ID_LOG      = 0x0002,   // Менеджер логирования
    MODULE_ID_DEVICE   = 0x0003,   // Менеджер устройств (I2C, SPI, Ethernet)
    MODULE_ID_RTC      = 0x0004,   // Часы реального времени (DS3231)

    // === АППАРАТУРНЫЕ МОДУЛИ (0x0005 - 0x000F) ===
    MODULE_ID_WIEGAND  = 0x0005,   // Считыватель карт (Wiegand)
    MODULE_ID_AUDIO    = 0x0006,   // Аудио-плеер (DFPlayer Mini)
    MODULE_ID_AUDIO_EXT = 0x0007,  // Расширения аудио (озвучивание)
    MODULE_ID_DIMMER   = 0x0008,   // Управление диммером (PWM)
    MODULE_ID_LOCAL_INPUT = 0x0009, // Локальные входы (кнопки, датчики)

    // === СЕТЕВЫЕ МОДУЛИ (0x0010 - 0x001F) ===
    MODULE_ID_MQTT     = 0x0010,   // MQTT клиент
    MODULE_ID_WEB      = 0x0011,   // Веб-сервер
    MODULE_ID_OTA      = 0x0012,   // Обновление прошивки (OTA)

    // === БЕЗОПАСНОСТЬ (0x0020 - 0x002F) ===
    MODULE_ID_USER     = 0x0020,   // Управление пользователями (СКУД)

    // === СИСТЕМНЫЕ СЕРВИСЫ (0x0030 - 0x003F) ===
    MODULE_ID_PAZ      = 0x0030,   // Противоаварийная защита (ПАЗ)
    MODULE_ID_TEMP_SENSOR = 0x0031, // Датчик температуры ESP32
    MODULE_ID_DATALOGGER = 0x0032,  // Логирование данных

    // === ПРИЛОЖЕНИЯ (0x1000 - 0x1FFF) ===
    MODULE_ID_APP_BASE = 0x1000,    // Базовый ID для приложений
    MODULE_ID_SMART_LIGHT = 0x1001, // Умный свет
    MODULE_ID_SMART_LOCK  = 0x1002, // Умный замок (СКУД)
    MODULE_ID_SMART_COUNTER = 0x1003, // Умный счетчик
    MODULE_ID_SMART_CLIMATE = 0x1004, // Умный климат
    MODULE_ID_WEATHER_GATE = 0x1005,  // Погодный шлюз

    MODULE_ID_MAX = 0xFFFF  // Максимальный ID (для проверок)
};

// ============================================================================
// 4. СИСТЕМНЫЕ СОБЫТИЯ
// ============================================================================
/**
 * @brief Идентификаторы системных событий
 *
 * Эти события обрабатываются ядром и модулями.
 * Пользовательские события должны начинаться с SH_EVENT_USER_BASE (4096).
 *
 * ВАЖНО: SH_EVENT_CMD_EXECUTE (2457) и SH_EVENT_CMD_RESPONSE (2464)
 * зарезервированы для командной системы.
 */
enum SystemEventIds : int32_t {
    // === ЖИЗНЕННЫЙ ЦИКЛ (0-3) ===
    SH_EVENT_SYS_BOOT          = 0,     // Система загружается
    SH_EVENT_SYS_READY         = 1,     // Система готова к работе
    SH_EVENT_SYS_SHUTDOWN      = 2,     // Система выключается
    SH_EVENT_SYS_RESTART       = 3,     // Система перезагружается

    // === СОБЫТИЯ МОДУЛЕЙ (4-8) ===
    SH_EVENT_MODULE_REGISTERED = 4,     // Модуль зарегистрирован в ядре
    SH_EVENT_MODULE_INIT_START = 5,     // Начало инициализации модуля
    SH_EVENT_MODULE_INIT_DONE  = 6,     // Инициализация завершена
    SH_EVENT_MODULE_ERROR      = 7,     // Ошибка в модуле
    SH_EVENT_MODULE_TICK       = 8,     // Периодический вызов (тик)

    // === СОБЫТИЯ СЕТИ (9-11) ===
    SH_EVENT_NET_CONNECTED     = 9,     // Сеть подключена
    SH_EVENT_NET_DISCONNECTED  = 10,    // Сеть отключена
    SH_EVENT_NET_IP_CHANGED    = 11,    // IP-адрес изменился

    // === СОБЫТИЯ ЗДОРОВЬЯ (12-15) ===
    SH_EVENT_HEALTH_OK         = 12,    // Все хорошо
    SH_EVENT_HEALTH_WARNING    = 13,    // Предупреждение
    SH_EVENT_HEALTH_CRITICAL   = 14,    // Критическое состояние
    SH_EVENT_HEALTH_RESTORED   = 15,    // Здоровье восстановлено

    // === СОБЫТИЯ ВРЕМЕНИ (16-18) ===
    SH_EVENT_TIME_SYNC         = 16,    // Время синхронизировано
    SH_EVENT_TIME_CHANGED      = 17,    // Время изменилось
    SH_EVENT_TEMPERATURE_UPDATE = 18,   // Обновление температуры

    // === КОМАНДНАЯ СИСТЕМА (специальные ID) ===
    SH_EVENT_CMD_EXECUTE       = 2457,  // Выполнить команду (0x0999)
    SH_EVENT_CMD_RESPONSE      = 2464,  // Ответ на команду (0x09A0)

    // === СТАТУСЫ МОДУЛЕЙ (пользовательские) ===
    // SH_EVENT_MODULE_STATUS     = 0x1000 // Статус модуля (вместо SH_EVENT_MODULE_TICK)
};

// ============================================================================
// 5. КОМАНДЫ МОДУЛЕЙ
// ============================================================================
/**
 * @brief Стандартные команды для взаимодействия с модулями
 *
 * Каждый модуль может расширять этот список своими командами.
 * Команды с битом 0x8000 считаются ответами.
 */
enum ModuleCommands : uint32_t {
    CMD_GET_STATUS    = 0x0001,   // Запрос статуса модуля
    CMD_GET_CONFIG    = 0x0002,   // Запрос конфигурации
    CMD_SET_CONFIG    = 0x0003,   // Установка конфигурации
    CMD_SAVE_CONFIG   = 0x0004,   // Сохранение конфигурации
    CMD_RESET_CONFIG  = 0x0005,   // Сброс конфигурации
    CMD_GET_DIAG      = 0x0006,   // Запрос диагностики
    CMD_RESPONSE_OK   = 0x8001,   // Успешный ответ
    CMD_RESPONSE_ERROR = 0x8002,  // Ошибка
    CMD_RESPONSE_DATA = 0x8003,   // Данные в ответе
};

// ============================================================================
// 6. БАЗОВЫЙ ИНТЕРФЕЙС
// ============================================================================
/**
 * @brief Базовый класс для всех модулей системы
 *
 * Все модули должны наследоваться от этого класса и реализовывать
 * все виртуальные методы. Модули не должны иметь прямых ссылок
 * на другие модули - только через события.
 */
class IModule {
public:
    virtual ~IModule() = default;

    // === ЖИЗНЕННЫЙ ЦИКЛ ===
    /**
     * @brief Инициализация модуля (вызывается один раз при старте)
     *
     * Здесь должна происходить инициализация аппаратуры,
     * загрузка конфигурации, подготовка ресурсов.
     * Не блокировать надолго (использовать таймауты)!
     */
    virtual void init() = 0;

    /**
     * @brief Запуск модуля (после всех init)
     *
     * Здесь начинается основная работа модуля.
     * Можно создавать задачи FreeRTOS, подписываться на события.
     */
    virtual void start() = 0;

    /**
     * @brief Остановка модуля (при перезагрузке или выключении)
     *
     * Должна быть корректная остановка всех задач,
     * освобождение ресурсов, сохранение состояния.
     */
    virtual void stop() = 0;

    /**
     * @brief Периодический вызов (тик системы)
     *
     * Вызывается ядром с интервалом tickInterval.
     * Используется для фоновых задач, опроса датчиков,
     * проверки состояния. Не блокировать надолго!
     */
    virtual void tick() = 0;

    // === ОБРАБОТКА СОБЫТИЙ ===
    /**
     * @brief Обработчик событий
     * @param eventId ID события
     * @param data Данные события (может быть nullptr)
     *
     * Все взаимодействие между модулями происходит через этот метод.
     * Модуль должен проверить eventId и data->targetModule.
     * Не блокировать надолго! Если нужна долгая обработка -
     * создать задачу или использовать очередь.
     */
    virtual void onEvent(int32_t eventId, const ShEventData* data) = 0;

    /**
     * @brief Проверка, может ли модуль обработать событие
     * @param eventId ID события
     * @return true если модуль может обработать событие
     *
     * Используется ядром для фильтрации событий.
     * Должна быть быстрой (без блокировок).
     */
    virtual bool canHandleEvent(int32_t eventId) const = 0;

    // === ИДЕНТИФИКАЦИЯ ===
    /**
     * @brief Получить имя модуля
     * @return Строка с именем модуля
     */
    virtual const char* getName() const = 0;

    /**
     * @brief Получить версию модуля
     * @return Строка с версией (формат "x.y.z")
     */
    virtual const char* getVersion() const = 0;

    /**
     * @brief Получить ID модуля
     * @return Уникальный ID (из enum ModuleIds)
     */
    virtual uint32_t getModuleId() const = 0;

    // === СТАТУС ===
    /**
     * @brief Проверить готовность модуля
     * @return true если модуль готов к работе
     */
    virtual bool isReady() const = 0;

    /**
     * @brief Получить строку со статусом модуля
     * @return Строка статуса (например, "OK", "ERROR", "INIT")
     */
    virtual const char* getStatus() const = 0;

    /**
     * @brief Получить диагностическую информацию
     * @param data Указатель на структуру для заполнения
     *
     * Заполняет ShEventData диагностической информацией.
     * Используется для удаленной диагностики.
     */
    virtual void getDiagnostics(ShEventData* data) const = 0;

    // === ОТПРАВКА СООБЩЕНИЙ ===
    /**
     * @brief Отправить событие в систему
     * @param eventId ID события
     * @param data Данные события (может быть nullptr)
     *
     * Безопасная отправка события. Автоматически определяет
     * контекст (задача или ISR) и выбирает правильный метод.
     */
    void postEvent(int32_t eventId, const ShEventData* data = nullptr) const;

    /**
     * @brief Отправить команду модулю
     * @param targetModuleId ID целевого модуля
     * @param command Код команды
     * @param value Числовое значение
     * @param payload Строковые данные (может быть nullptr)
     *
     * Удобная обертка для отправки команд.
     * Автоматически заполняет sourceModule.
     */
    void sendCommand(uint32_t targetModuleId, uint32_t command,
                    int32_t value = 0, const char* payload = nullptr) const;

    /**
     * @brief Отправить ответ на команду
     * @param targetModuleId ID модуля, которому отвечаем
     * @param command Код команды (с битом 0x8000)
     * @param value Числовое значение
     * @param payload Строковые данные (может быть nullptr)
     *
     * Автоматически устанавливает бит 0x8000 в command.
     */
    void sendResponse(uint32_t targetModuleId, uint32_t command,
                     int32_t value = 0, const char* payload = nullptr) const;

    /**
     * @brief Отправить статус модуля
     * @param status Строка статуса (если nullptr, отправляется "OK")
     *
     * Удобный метод для публикации статуса всем модулям.
     * Использует событие SH_EVENT_MODULE_STATUS.
     */
    void sendStatus(const char* status = nullptr) const;

    /**
     * @brief Отправить ошибку
     * @param errorCode Код ошибки
     * @param errorMessage Сообщение об ошибке
     *
     * Унифицированная отправка ошибок.
     * Использует событие SH_EVENT_MODULE_ERROR.
     */
    void sendError(uint32_t errorCode, const char* errorMessage) const;

    // === ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ ===
    bool isInitialized() const { return _initialized; }
    void setInitialized(bool state) { _initialized = state; }

    bool isReadyFlag() const { return _ready; }
    void setReadyFlag(bool state) { _ready = state; }

protected:
    bool _initialized = false;  // Флаг инициализации
    bool _ready = false;        // Флаг готовности
    uint32_t _moduleId = 0;     // ID модуля (устанавливается в конструкторе)
};

// ============================================================================
// 7. ВСПОМОГАТЕЛЬНЫЕ МАКРОСЫ ДЛЯ МОДУЛЕЙ
// ============================================================================
/**
 * @brief Макрос для удобного объявления модуля
 *
 * Использование:
 * DECLARE_MODULE(MyModule, MODULE_ID_MY_MODULE, "1.0.0")
 */
#define DECLARE_MODULE(className, moduleId, versionStr) \
    public: \
        const char* getName() const override { return #className; } \
        const char* getVersion() const override { return versionStr; } \
        uint32_t getModuleId() const override { return moduleId; } \
    private:

/**
 * @brief Макрос для проверки готовности модуля в обработчиках
 *
 * Использование:
 * if (!CHECK_MODULE_READY(this)) return;
 */
#define CHECK_MODULE_READY(instance) \
    ((instance) && (instance)->isReady())

/**
 * @brief Макрос для безопасной отправки события
 *
 * Использование:
 * SEND_EVENT_SAFE(SH_EVENT_SYS_READY, nullptr);
 */
#define SEND_EVENT_SAFE(eventId, data) \
    if (isReady()) { postEvent(eventId, data); }

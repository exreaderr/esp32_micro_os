// Фаза 0. Чистый контракт: что Kernel ожидает от каждого модуля системы
// (системного сервиса, транспорта, доменного сервиса, приложения).
//
// Расширенный жизненный цикл (базовая архитектура, раздел 8.6):
//
//   describe()            — модуль объявляет зависимости и возможности.
//                           НЕ трогает железо и другие сервисы.
//   registerExtensions()  — инжекция: конфиг-схема, API, HA-сущности,
//                           health-checks, UI-виджеты. Все модули завершают
//                           эту фазу ДО первого init().
//   init()                — инициализация ресурсов; конфиг уже доступен.
//   start()               — рабочий режим: подписки на события, задачи.
//   tick()                — периодический вызов из Kernel с периодом модуля.
//   stop()                — остановка (перед ребутом/остановкой подсистемы).
//
// События: модуль получает ТОЛЬКО те eventId, на которые подписался через
// EventBus::subscribe() (обычно в start()).
// ============================================================================
#pragma once

#include <cstdint>
#include "ShTypes.h"

class IModule {
public:
    virtual ~IModule() = default;

    // --- ИДЕНТИЧНОСТЬ ----------------------------------------------------
    virtual const char* getName() const = 0;        // "ConfigService"
    virtual const char* getVersion() const = 0;     // "5.0.0"
    virtual ModuleId getModuleId() const = 0;       // 0x0001...

    // --- ЖИЗНЕННЫЙ ЦИКЛ ----------------------------------------------------
    /// Фаза 0 жизненного цикла: объявить зависимости/возможности.
    /// По умолчанию пустой — реализуют модули с зависимостями.
    virtual void describe() {}

    /// Фаза 1: инжекция в системные сервисы (конфиг, API, HA, UI, ПАЗ).
    virtual void registerExtensions() {}

    /// Фаза 2: инициализация (железо сервиса, файлы, задачи).
    virtual void init() = 0;

    /// Фаза 3: старт рабочего режима (подписки EventBus здесь).
    virtual void start() = 0;

    /// Периодическая работа. Вызывается Kernel не чаще getTickIntervalMs().
    virtual void tick() = 0;

    /// Остановка. Должен снять подписки: EventBus::unsubscribeAll(this).
    virtual void stop() = 0;

    // --- СОБЫТИЯ -------------------------------------------------------------
    /// Обработчик события. Вызывается из задачи-диспетчера EventBus —
    /// значит, НЕ из контекста loop() и НЕ из ISR: внутри можно
    /// пользоваться очередями и короткими критическими секциями,
    /// но нельзя надолго блокироваться (бюджет — см. B2).
    virtual void onEvent(int32_t eventId, const ShEventData* data) = 0;

    /// Предохранительный фильтр (дублирует подписку). Быстрый — вызывается
    /// на каждое доставленное событие.
    virtual bool canHandleEvent(int32_t eventId) const = 0;

    // --- СОСТОЯНИЕ --------------------------------------------------------------
    /// Готов ли модуль к работе (после start без ошибок).
    virtual bool isReady() const = 0;

    /// Период вызова tick(), мс. 0 — тикать каждый цикл Kernel (осторожно).
    virtual uint32_t getTickIntervalMs() const { return 100; }
};

#pragma once

#include <cstdint>

namespace bcd {

/// BCD -> двоичное: 0x25 -> 25
inline uint8_t toBin(uint8_t b) { return (uint8_t)((b >> 4) * 10 + (b & 0x0F)); }

/// Двоичное -> BCD: 25 -> 0x25 (вход 0..99; иное — UB вызывающего)
inline uint8_t toBcd(uint8_t b) { return (uint8_t)(((b / 10) << 4) | (b % 10)); }

} // namespace bcd

// ============================================================================
// BaseProfile.h — АППАРАТНАЯ БАЗА ПЛАТФОРМЫ: WT32-ETH01 + DS3231
// ============================================================================
// Фаза 0. Фиксирует единственную аппаратную платформу экосистемы.
// Этот файл НЕ является IDeviceProfile — ядро использует его константы
// напрямую при регистрации ресурсов платформы (до старта любого профиля).
// Профили устройств только ДОБАВЛЯЮТ периферию поверх этой базы.
//
// Проверено по монолиту smart_lock v2.5.0 (WT32-ETH01, часть 1).
// ============================================================================
#pragma once

#include <cstdint>

namespace platform {

// ============================================================================
// ETHERNET (WT32-ETH01, PHY LAN8720)
// ============================================================================
// Полный набор RMII-пинов фиксирован платой WT32-ETH01 и не может быть
// переназначен — поэтому в реестр заносится только power-пин PHY (его
// дергает NetworkManager при инициализации), а RMII-пины документируются.
constexpr uint8_t ETH_PHY_POWER_PIN = 16;  // GPIO16: питание PHY LAN8720
// RMII (документально, не заносятся в реестр — аппаратно фиксированы):
//   TXD0=21, TXD1=19, TX_EN=22, RXD0=25, RXD1=26, CRS_DV=27, MDC=23, MDIO=18
//   CLK: внешний генератор платы 50 МГц -> вход GPIO0 (ETH_CLOCK_GPIO0_IN,
//        каноническая конфигурация WT32-ETH01). GPIO0 как GPIO не использовать!
//        Альтернатива для иных ревизий платы: ETH_CLOCK_GPIO17_OUT.

// ============================================================================
// I2C (системная шина: DS3231 + расширения)
// ============================================================================
constexpr uint8_t  I2C_SDA_PIN    = 32;    // GPIO32
constexpr uint8_t  I2C_SCL_PIN    = 33;    // GPIO33
constexpr uint32_t I2C_FREQ_HZ    = 400000; // 400 кГц (проверено монолитом)
constexpr uint8_t  DS3231_ADDR    = 0x68;  // RTC на системной шине

// ============================================================================
// КОНСОЛЬ
// ============================================================================
constexpr uint8_t  CONSOLE_UART   = 0;     // UART0: Serial-консоль/прошивка

// ============================================================================
// ЗАРЕЗЕРВИРОВАННЫЕ/ОПАСНЫЕ ПИНЫ (документация для авторов профилей)
// ============================================================================
// GPIO 1, 3   — UART0 (консоль)
// GPIO 16     — питание PHY
// GPIO 21,19,22,25,26,27,23,18 — RMII Ethernet (см. выше)
// GPIO 32, 33 — системная I2C
// GPIO 34,35,36,39 — только входы (без внутренней подтяжки!) — использовать
//                    для герконов/кнопок/BUSY с внешней подтяжкой.
// Свободны для профилей: 2, 4, 5, 12, 13, 14, 15, 17 (+ входные 34-39).

// ============================================================================
// МУЛЬТИПЛАТФОРМЕННОСТЬ (5.3.0, проверка переносимости A4)
// ============================================================================
// Платформа больше не одна: профиль объявляет плату в HardwareManifest
// (boardId), Kernel вызывает selectBoard() ДО поднятия ресурсов/шин,
// а BusManager/NetworkService читают пины из board() вместо констант.
// Константы WT32-ETH01 выше оставлены как дефолт и документацию.
// ============================================================================

enum class BoardId : uint8_t {
    Wt32Eth01       = 0,   // базовая (классический ESP32, RMII LAN8720)
    Esp32S3PoeEth   = 1,   // Waveshare ESP32-S3-POE-ETH (S3R8, W5500, SD)
    Esp32C3SuperMini = 2,  // ESP32-C3 SuperMini (RISC-V, без сети — узел шины)
};

enum class EthKind : uint8_t {
    RmiiLan8720 = 0,     // внутренний EMAC + внешний PHY (только классика)
    SpiW5500    = 1,     // внешний MAC/PHY по SPI (S3 своего EMAC не имеет)
    None        = 2,     // Ethernet НЕТ фактом железа (узел шины RS485):
                         // NetworkService принудительно в локальный режим
                         // (честный AUTONOMOUS без аварий), HTTP/MQTT не
                         // стартуют — конфигурация и данные идут по шине.
};

/// Описание платы: всё, что ядру нужно знать о железе до старта профиля.
struct BoardDesc {
    BoardId id;
    const char* name;        // для логов/UI: "WT32-ETH01" и т.п.

    // Системная I2C (DS3231, адрес 0x68 — общий для всех плат)
    uint8_t i2cSda;
    uint8_t i2cScl;

    // Ethernet
    EthKind ethKind;
    int8_t  ethPowerPin;     // RMII: питание PHY (-1 у W5500)
    int8_t  ethCs;           // SPI: CS  (-1 у RMII)
    int8_t  ethIrq;          // SPI: INT
    int8_t  ethRst;          // SPI: RST
    int8_t  ethSck, ethMiso, ethMosi;
    uint8_t ethSpiHost;      // spi_host_device_t (SPI2_HOST=1)

    // microSD-слот (нет на WT32-ETH01)
    bool    sdPresent;
    int8_t  sdCs, sdSck, sdMiso, sdMosi;
    uint8_t sdSpiHost;       // нумерация Arduino-SPIClass! (не IDF: на S3 SPI3 = 1)
};

/// Описание платы по идентификатору (таблица плат — в BaseProfile.cpp).
const BoardDesc& boardDesc(BoardId id);

/// Текущая плата. До selectBoard() — Wt32Eth01 (безопасный дефолт:
/// все вызовы board() до boot-манифеста получают историческую базу).
const BoardDesc& board();

/// Выбор платы. Вызывается Kernel::boot() сразу после describeHardware()
/// и ДО claim'а ресурсов платформы, BusManager и NetworkService.
void selectBoard(BoardId id);

// ============================================================================
// ПЛАТА ESP32-S3-POE-ETH (BoardId::Esp32S3PoeEth) — документация пинов
// ============================================================================
// W5500 (SPI2_HOST): MOSI=11, MISO=12, SCLK=13, CS=14, RST=9, INT=10
// microSD (периферия SPI3 = Arduino SPIClass(1), ОТДЕЛЬНАЯ шина): CS=4, MOSI=6, MISO=5, SCK=7
// DS3231: I2C SDA=16, SCL=17 (пины разъёма, выбраны на M0; камера 47/48
//         не конфликтует — у неё свой SCCB на других пинах)
// Запрещены: GPIO33–37 (octal PSRAM), GPIO26–32 (SPI flash/PSRAM),
//            GPIO43/44 — UART0 консоль; GPIO0 — BOOT (safeModePin).
// ============================================================================
// ПЛАТА ESP32-C3 SUPERMINI (BoardId::Esp32C3SuperMini) — документация
// ============================================================================
// Роль: узел проводной шины (RS485) — Помощник ветки smart_light и другие
// нижнеуровневые контроллеры. Сети НЕТ фактом железа (EthKind::None);
// радио глушится «отсутствием кода» — как везде в парке (урок 5.3.2).
//
// Кристалл: ESP32-C3 (RISC-V, 1 ядро, 160 МГц), 4 МБ flash, ~400 КБ SRAM.
// Кооперативная модель ядра (один loopTask) ложится идеально; FreeRTOS
// unicore учтён ядром изначально.
//
// Разведено на модуле: GPIO0–10, 20, 21. Системные назначения ядра:
//   · консоль/лог: USB-CDC (внутренний USB на GPIO18/19, FQBN CDCOnBoot=cdc);
//     UART0 (RX=20, TX=21) остаётся запасным каналом стенда;
//   · системная I2C (DS3231 и датчики): SDA=6, SCL=7 (выбор платформы;
//     GPIO4–7 — ещё и classic JTAG, мы его не используем).
// Осторожно/запрещено:
//   · GPIO8  — бортовой LED (активен НИЗКИМ) + страппинг (на boot = высокий);
//   · GPIO9  — BOOT (страппинг); GPIO2 — страппинг (на boot = высокий);
//   · GPIO11–17 — встроенная SPI-флеш (на модуль не разведены, но и в
//     реестр профилям не отдавать).
// Свободно для профиля (все с учётом страппинга): 0, 1, 3, 4, 5, 10, 20, 21
// + 2 при гарантированном высоком уровне на boot. UART1 (матрица GPIO) —
// кандидат под RS485 full-duplex (TX/RX/DE), выбор пинов — за профилем.
// PCNT у C3 НЕТ — драйверы, опирающиеся на PCNT, на этой плате не живут.
// ============================================================================

} // namespace platform

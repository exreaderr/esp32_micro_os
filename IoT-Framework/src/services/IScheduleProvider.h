// ============================================================================
// Базовая архитектура, §9 (точки расширения): «Задачи планировщика |
// Scheduler | Временные правила (ночной режим и т.п.) | IScheduleProvider».
//
// Зачем, если есть конфиг-правила sched.rule0..3: профиль может ЗАФИКСИРОВАТЬ
// правило в коде (например, «ночной режим сирены ПАЗ»), не отдавая его на
// откуп веб-редактору: такое правило видно в списке, работает наравне с
// конфигурационными, но не стирается пользователем и переживает сброс
// конфигурации.
//
// Реализация живёт в профиле (или доменном сервисе), регистрация:
//   ScheduleService::getInstance().setProvider(&myProvider);
// — до start() сервиса (профильные модули регистрируются в ядре после
// системных, поэтому фаза registerExtensions/init профиля — подходящее
// место). Правила провайдера добавляются ПОСЛЕ конфиг-правил; суммарно
// не больше SCHED_MAX_RULES (лишние молча отбрасываются + счётчик).
// ============================================================================
#pragma once

#include <cstdint>
#include "ScheduleCore.h"

class IScheduleProvider {
public:
    virtual ~IScheduleProvider() = default;

    /// Сколько правил отдаёт провайдер (0..4; больше — обрежется).
    virtual uint8_t getScheduleRuleCount() const = 0;

    /// Копия правила idx в out. false — idx вне диапазона (правило
    /// пропускается). Вызывается при каждой перезагрузке правил
    /// (смена sched.* в конфиге), поэтому ДЕШЁВАЯ: без malloc/FS.
    virtual bool getScheduleRule(uint8_t idx, SchedRule& out) const = 0;
};

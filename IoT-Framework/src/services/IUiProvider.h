// ============================================================================
// Принцип МикроОС 5.0: ядро владеет МЕХАНИЗМОМ, профиль — СОДЕРЖАНИЕМ.
// Веб-интерфейс разделён на две части (решение пользователя):
//
//   · УНИВЕРСАЛЬНАЯ (админская): сеть, параметры из ConfigService-схем,
//     телеметрия, журналы, аудит, OTA. Строится HttpService'ом автоматически,
//     доступна ТОЛЬКО по ПИН-коду администратора (AuthService + C1/C3).
//     Профиль о ней не знает и знать не должен.
//
//   · ПРОФИЛЬНАЯ (публичная): лицо конкретного устройства. Для большинства
//     устройств — открыта всем; для СКУД — по профильному ПИН-коду
//     (политику доступа решает сам провайдер, ядро даёт ему запрос целиком).
//
// Профиль реализует этот интерфейс и передаёт его в
// HttpService::setUiProvider() из registerExtensions() своего модуля —
// ровно как конфиг-схемы инжектятся в ConfigService.
// ============================================================================
#pragma once

#include <cstddef>

// ============================================================================
// КОНТЕКСТ ПРОФИЛЬНОГО ЗАПРОСА (передаётся провайдеру целиком)
// ============================================================================
// Зачем структура, а не «заголовок через lastToken()»: профильному API нужны
// метод и АРГУМЕНТЫ (CRUD карт СКУД, дистанционное открытие с ПИНом).
// <WebServer.h> в интерфейс не тащим — доступ к аргументам через колбэк,
// чтобы провайдер оставался тестируемым и независимым от транспорта.
struct ShUiRequest {
    const char* method;      // "GET" | "POST" | ...
    const char* token;       // X-Auth-Token ядерной админ-сессии (или "")
    /// Аргумент запроса (query или form) по имени. nullptr — нет такого.
    /// ВНИМАНИЕ: возвращённый указатель живёт до следующего вызова arg()
    /// (кольцевой буфер транспорта) — скопируйте значение сразу.
    const char* (*arg)(void* ctx, const char* name);
    void* argCtx;

    /// Синтаксический сахар с проверкой наличия.
    const char* getArg(const char* name) const {
        return arg ? arg(argCtx, name) : nullptr;
    }
};

class IUiProvider {
public:
    virtual ~IUiProvider() = default;

    /// Имя устройства для заголовка публичной страницы ("smart_lock").
    virtual const char* uiTitle() const = 0;

    /// HTML-секция профиля для публичной страницы "/" (без <html>/<body> —
    /// фрагмент внутри карточки, бюджет ~2 КБ). Возвращает записанную длину.
    /// Буфер вызывающего, без String/heap.
    virtual size_t renderPublicHtml(char* buf, size_t bufSize) = 0;

    /// Профильный API: запросы "/api/dev/<tail>" отдаются сюда.
    /// pathTail — путь после "/api/dev/". Ответ — JSON в буфер вызывающего,
    /// statusCode — HTTP-код (200/400/401...).
    /// true — запрос обработан; false — 404 (нет такого профильного пути).
    /// Авторизация — забота провайдера: админская сессия ядра проверяется
    /// через HttpService::isAdminToken(req.token), профильный ПИН (СКУД) —
    /// собственной политикой провайдера (C3: через rate-limiter AuthService).
    virtual bool handleApi(const char* pathTail, const ShUiRequest& req,
                           char* responseBuf, size_t bufSize,
                           int& statusCode) = 0;
};

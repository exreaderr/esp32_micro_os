def tts_request(text, folder_name, file_id):
    # Корректный шлюз API v3 REST
    url = "https://tts.api.cloud.yandex.net/tts/v3/utteranceSynthesis"

    headers = {
        "Authorization": f"Api-Key {API_KEY}",
        "x-folder-id": FOLDER_ID,
        "Content-Type": "application/json"
    }

    data = {
        "text": text,
        "modelRole": "friendly", # Включаем мягкое, дружелюбное амплуа для Марины
        "hints": [
            {"voice": "marina"},  # Переключили на великолепный женский голос marina
            {"speed": 1.0}
        ],
        "outputAudioSpec": {
            "containerAudio": {
                "containerAudioType": "MP3"
            }
        }
    }

    response = requests.post(url, headers=headers, json=data)
    if response.status_code == 200:
        # 1. Извлекаем из пришедшего JSON чистые бинарные аудиобайты MP3
        json_data = response.json()
        base64_str = json_data["result"]["audioChunk"]["data"]

        import base64
        clean_mp3_bytes = base64.b64decode(base64_str)

        # 2. УДАЛЯЕМ ЗНАК ПЛЮСА '+' ИЗ ИМЕНИ ДЛЯ ВАШЕГО УДОБСТВА
        # Метод replace('+', '') уберет знак ударения, оставив "Александр" вместо "Алекс+андр"
        clean_name_text = text.replace('+', '')

        # 3. ФОРМИРУЕМ КРАСИВОЕ ИМЯ ФАЙЛА ПРОМЫШЛЕННОГО СТАНДАРТА
        # Результат: "001_Александр.mp3", "011_Внимание! Дверь не закрыта.mp3"
        filename = f"{file_id}_{clean_name_text}.mp3"
        full_path = os.path.join(folder_name, filename)

        # 4. Записываем монолитный музыкальный файл на диск
        with open(full_path, "wb") as f:
            f.write(clean_mp3_bytes)

        print(f"[УСПЕХ] Сгенерирован: {full_path} -> '{text}'")



// Что здесь и почему:
//   1. ShEventData  — единый формат данных события шины. ФИКСИРОВАННЫЙ размер:
//      никаких String и malloc — событие копируется побайтово и может летать
//      из ISR, не фрагментируя кучу (урок v4.2.2: String в горячих структурах
//      = фрагментация heap).
//   2. LogLevel     — enum class, чтобы константы НЕ совпадали по имени с
//      макросами логирования (в v4.2.2 LOG_DEBUG был одновременно enum и
//      макросом — конфликт препроцессора, который чинит эта версия).
//   3. HealthResult — вердикт доменной проверки ПАЗ (IHealthCheck).
//   4. ModuleId     — тип идентификаторов модулей (диапазоны, как у событий).

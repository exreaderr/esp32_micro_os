#pragma once

#include <cstdint>
#include <cstddef>

// ============================================================================
// 1. ДАННЫЕ СОБЫТИЯ (единый контейнер шины)
// ============================================================================

/// Максимальная длина текстового payload события (без '\0').
/// 47 байт хватает на HEX-карту (8), IP-адрес (15), имя топика (32) и т.п.
/// Если данных больше — они передаются командой (CMD_EXECUTE) или через
/// сервис-владельца, а не через шину.
constexpr size_t SH_EVENT_PAYLOAD_SIZE = 48;

struct ShEventData {
    uint32_t sourceModule;              // MODULE_ID отправителя (0 = ядро)
    int32_t  code;                      // числовой контекст: код ошибки,
                                        // значение, индекс — зависит от события
    uint32_t timestampMs;               // millis() на момент публикации
    char     payload[SH_EVENT_PAYLOAD_SIZE];  // короткий текст ('\0'-terminated)

    /// Быстрая инициализация пустого события от ядра.
    void clear() {
        sourceModule = 0;
        code = 0;
        timestampMs = 0;
        payload[0] = '\0';
    }
};

static_assert(sizeof(ShEventData) <= 64,
    "ShEventData must stay small: it travels through the queue by copy");

// ============================================================================
// 2. УРОВНИ ЛОГИРОВАНИЯ
// ============================================================================

/// enum class — имена НЕ попадают в глобальную область видимости.
/// Обращение: LogLevel::Debug. Макросы ядра — SH_LOG_D/SH_LOG_I/...,
/// поэтому конфликт "макрос == константа enum" из v4.2.2 исключён.
enum class LogLevel : uint8_t {
    Debug    = 0,   // отладочный шум (отключаемо в релизе)
    Info     = 1,   // штатные события жизненного цикла
    Warning  = 2,   // аномалия, система работает
    Error    = 3,   // сбой функции, модуль жив
    Critical = 4    // авария: вмешательство ПАЗ, потеря данных, ребут
};

// ============================================================================
// 3. ВЕРДИКТ ПРОВЕРКИ ЗДОРОВЬЯ (для IHealthCheck / HealthMonitor)
// ============================================================================

struct HealthResult {
    enum class Status : uint8_t { Ok, Warning, Critical } status;
    char message[32];                   // "RELAY_STICK_ALARM" и т.п.

    static HealthResult ok() {
        HealthResult r; r.status = Status::Ok; r.message[0] = '\0'; return r;
    }
    static HealthResult warning(const char* msg) {
        HealthResult r; r.status = Status::Warning;
        copyMsg(r.message, msg); return r;
    }
    static HealthResult critical(const char* msg) {
        HealthResult r; r.status = Status::Critical;
        copyMsg(r.message, msg); return r;
    }
private:
    static void copyMsg(char* dst, const char* src) {
        size_t i = 0;
        // Размер буфера — поле структуры: sizeof(dst) здесь дал бы размер
        // УКАЗАТЕЛЯ (классическая ловушка), поэтому sizeof(HealthResult::message).
        for (; src && src[i] && i < sizeof(HealthResult::message) - 1; ++i)
            dst[i] = src[i];
        dst[i] = '\0';
    }
};

// ============================================================================
// 4. ИДЕНТИФИКАТОРЫ МОДУЛЕЙ
// ============================================================================
// Диапазоны MODULE_ID (выдаёт ResourceManager::claimEventRange вместе с
// диапазоном событий — модуль и его события регистрируются парой):
//   0x0000          — ядро (Kernel)
//   0x0001–0x00FF   — системные сервисы
//   0x0100–0x01FF   — транспорт
//   0x0200–0x02FF   — доменные сервисы
//   0x1000+         — приложения профилей
using ModuleId = uint32_t;

constexpr ModuleId MODULE_ID_KERNEL = 0x0000;

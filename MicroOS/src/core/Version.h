// Урок 5.0.10: «Текущая прошивка ee57070» — это git-хэш ЯДРА Arduino из
// esp_app_desc_t, он одинаков для ВСЕХ сборок МикроОС. По нему отличить
// 5.0.8 от 5.0.9 нельзя — оператор прошил только FS и не мог это заметить
// (панель новая, прошивка старая, /api/config/backup -> 404 not_found).
// Версия МикроОС теперь зашивается здесь и показывается явно: в логе
// загрузки, в OTA-сведениях панели и в метаданных NVS-бэкапа.
// ПРАВИЛО РЕЛИЗА: бампать при КАЖДОЙ выдаче кита.
//
// MICROOS_BIN_TAG (5.0.12): строковая метка «MICROOS|x.y.z|END» зашивается
// в .bin — Build Master извлекает версию прямо из готового образа
// (grep -a) и декларирует её в version.json конвейера. Версия объявлена
// макросом, чтобы тег и константа не могли разойтись.
// ============================================================================
#pragma once

#define MICROOS_VERSION_STR "5.8.2"

constexpr const char* MICROOS_VERSION = MICROOS_VERSION_STR;

// used — иначе --gc-sections выбросит «ненужную» строку из rodata.
__attribute__((used)) constexpr const char MICROOS_BIN_TAG[] =
    "MICROOS|" MICROOS_VERSION_STR "|END";

// Ядерный бэклог 5.1.0 («PersistentCounter + PCNT»). Проблема монолита и
// 5.0.x: счётчик циклов замка писался в NVS на КАЖДОМ цикле (cfgGetUInt +
// setInternal). NVS на ESP32 — страничная структура во flash: запись живёт
// до стирания сектора (~100k циклов стирания). Замок на 50 циклов в сутки
// выжирал ресурс постоянно и без нужды — значение между ребутами терпит
// потерю нескольких инкрементов, а вот flash не терпит лишних записей.
//
// Решение: RAM-тень + батч-сброс. Здесь — только чистая политика «пора ли
// сбрасывать» и wrap-safe дельта аппаратного счётчика PCNT. Хранение,
// таймеры, PCNT-периферия — в CounterService (обёртка).
// ============================================================================
#pragma once

#include <cstdint>

// --- БЮДЖЕТЫ ------------------------------------------------------------------
constexpr uint8_t  CNT_MAX_COUNTERS = 8;    // счётчиков всего (cfg + NVS + PCNT)
constexpr uint8_t  CNT_NAME_LEN     = 16;   // лимит ключа NVS — 15 символов
constexpr uint32_t CNT_DEFAULT_FLUSH_EVERY      = 10;   // инкрементов
constexpr uint32_t CNT_DEFAULT_FLUSH_INTERVAL_S = 600;  // секунд

namespace cnt {

/// Политика батч-сброса: пора писать в NVS?
///   pending          — незаписанных инкрементов;
///   flushEvery       — порог по числу (0 — отключить порог);
///   msSinceFlush     — millis() с прошлого сброса (unsigned-вычитание
///                      вызывающего, wrap-safe);
///   flushIntervalMs  — порог по времени (0 — отключить).
/// Срабатывание ЛЮБОГО порога достаточно; pending==0 — не пишем никогда
/// (пустая запись = тот же износ без пользы).
inline bool shouldFlush(uint32_t pending, uint32_t flushEvery,
                        uint32_t msSinceFlush, uint32_t flushIntervalMs) {
    if (pending == 0) return false;
    if (flushEvery != 0 && pending >= flushEvery) return true;
    if (flushIntervalMs != 0 && msSinceFlush >= flushIntervalMs) return true;
    return false;
}

/// Дельта аппаратного счётчика PCNT между двумя чтениями.
/// Регистр PCNT — 16 бит со знаком, оборачивается на границах ±32767/−32768.
/// Арифметика (int16_t)(now − prev) корректна на любом wrap, пока за
/// интервал между чтениями набежало МЕНЬШЕ 32768 импульсов (при поллинге
/// раз в секунду — потолок 32 кГц, для бытовых счётчиков с запасом).
/// Отрицательная дельта (счётчик аппаратно обнулили снаружи) — не ошибка
/// кодирования; отбрасывать её — дело вызывающего.
inline int32_t pcntDelta(int16_t now, int16_t prev) {
    return (int32_t)(int16_t)(now - prev);
}

} // namespace cnt

// ============================================================================
// Фаза 1. Одна из точек расширения МикроОС 5.0 (базовая архитектура, 8.2):
// HealthMonitor владеет МЕХАНИЗМОМ (расписание, вердикты, WDT, эскалация),
// а модули и профили поставляют СОДЕРЖИМОЕ — проверки своего домена.
//
// Урок v4.2.2: там PazManager знал про СКУД (notifyCardScanned, дверь,
// реле) — доменная логика сидела в системном стороже. Здесь SmartLock
// регистрирует RelayStuckCheck/DoorAlarmCheck сам, ПАЗ о СКУД не знает.
// ============================================================================
#pragma once

#include "../core/ShTypes.h"

class IHealthCheck {
public:
    virtual ~IHealthCheck() = default;

    /// Имя проверки: "lock.relay_stuck", "sys.heap" — идёт в лог/HA/метрики.
    virtual const char* checkName() const = 0;

    /// Выполнить проверку. Должна быть быстрой (бюджет, как у tick — B2).
    /// HealthMonitor сам решает, что делать с вердиктом: WARNING — лог +
    /// событие, CRITICAL — событие + (для системных) эскалация.
    virtual HealthResult run() = 0;

    /// Период запуска, мс. Умолчание 1 с — подходит большинству проверок;
    /// редкие (целостность БД раз в сутки) переопределяют.
    virtual uint32_t intervalMs() const { return 1000; }
};

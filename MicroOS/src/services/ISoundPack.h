// Четвёртая точка инжекции МикроОС 5.0 (после IConfigProvider, IUiProvider,
// IHealthCheck): профиль описывает ЗВУКИ устройства ДАННЫМИ — таблицей
// «семантическое имя -> адрес на SD-карте». Кода здесь нет и быть не должно:
// смена озвучки/языка = другой SoundPack, прошивка не меняется.
//
// СТРУКТУРА SD-КАРТЫ (детерминировано на клоне MP3-TF-16P):
//   /01/001.mp3 ...  — обычные фразы (папки 01..99, треки 001..255);
//   /04/099.mp3      — напр. сирена СКУД (SIREN_FOLDER=4 из монолита);
//   /ADVERT/001.mp3  — папка ADVERT: аппаратный «прервать и продолжить».
//                      ВНИМАНИЕ: на клоне возврат к прерванному треку
//                      ненадёжен -> по умолчанию ADVERT-семантика эмулируется
//                      сервисом программно (audio.use_advert=false), а папка
//                      используется как обычное хранилище спец-фраз.
//
// СТАНДАРТНЫЕ СЛОТЫ ЯДРА (резерв семантических имён — профиль может
// определить их в паке, тогда ядро озвучивает системные события само):
//   "sys.boot"       — устройство загрузилось (после start());
//   "sys.safe_mode"  — вход в Safe Mode;
//   "sys.error"      — критическая ошибка;
//   "sys.alarm"      — системная тревога (SND_FLAG_LOOP рекомендован);
//   "auth.ok"        — успешная авторизация;
//   "auth.fail"      — неудачная попытка.
// Нет фразы в паке -> ядро молчит (это не ошибка).
// ============================================================================
#pragma once

#include <cstdint>
#include <cstring>
#include "AudioQueue.h"   // SND_FLAG_*, SndPriority, SND_NAME_LEN

// ============================================================================
// ФРАЗА: семантическое имя -> адрес на SD (+ политика)
// ============================================================================
struct SoundPhrase {
    const char* name;       // "access.granted" (или слот ядра "sys.boot")
    uint8_t     folder;     // папка на SD (1..99)
    uint8_t     track;      // трек в папке (1..255)
    uint8_t     priority;   // SndPriority (Alarm/Important/Normal/Ambient)
    uint8_t     flags;      // SND_FLAG_LOOP | SND_FLAG_ADVERT
};

// ============================================================================
// ПАКЕТ ФРАЗ УСТРОЙСТВА
// ============================================================================
class ISoundPack {
public:
    virtual ~ISoundPack() = default;

    /// Имя пакета для логов/диагностики ("smart_lock_ru_v1").
    virtual const char* packName() const = 0;
    /// Таблица фраз; count — число элементов.
    virtual const SoundPhrase* phrases(uint8_t& count) const = 0;

    /// Поиск фразы по имени (линейный — таблицы маленькие).
    /// nullptr — фраза не определена (вызывающий молчит/жалуется в лог).
    const SoundPhrase* find(const char* name) const {
        uint8_t n = 0;
        const SoundPhrase* table = phrases(n);
        for (uint8_t i = 0; i < n; ++i) {
            if (strncmp(table[i].name, name, SND_NAME_LEN) == 0) {
                return &table[i];
            }
        }
        return nullptr;
    }
};

#pragma once
#include <stdint.h>

namespace wxc {

// Порог 1.0 гПа/3ч: ниже — шум (точность BME280 ±0.12 гПа, уход RTC).
// Штормовой порог (>4 гПа/3ч) — W5, слот WG_EVENT_STORM_WARNING в ядре
// зарезервирован (Issue #1, 23.08).
inline int8_t baroTrend3h(float deltaHpa) {
    if (deltaHpa >  1.0f) return 1;
    if (deltaHpa < -1.0f) return -1;
    return 0;
}

} // namespace wxc
